  timestamp = Time.current.strftime('%Y%m%d_%H%M%S')
  name = scenario.respond_to?(:name) && scenario.name ? scenario.name : 'scenario'
  name = name.gsub(/^The\s*/i, '').gsub(/\s*Page/i, '')
  scenario_name = name.gsub(/[^0-9A-Za-z.-]/, '_')[0..100]

  # Determine path based on tags and status
