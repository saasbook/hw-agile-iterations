           'tmp/capybara/a11y'
         elsif scenario.failed?
           'tmp/capybara/failure'
         else
           'tmp/capybara/success'
         end

  # Create directory if it doesn't exist
  FileUtils.mkdir_p(Rails.root.join(path))

  # Save files
  page.save_page(Rails.root.join(path, "#{scenario_name}_#{timestamp}.html"))
